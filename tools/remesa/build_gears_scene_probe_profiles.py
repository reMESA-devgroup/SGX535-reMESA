"""Generate a separate exact gears LAB catalogue; no device or installation."""
import argparse, hashlib, json, struct
from pathlib import Path

def checked(path, digest, size=None):
 data=Path(path).read_bytes()
 if hashlib.sha256(data).hexdigest()!=digest or size is not None and len(data)!=size:
  raise ValueError('changed input: '+str(path))
 return data

def build(c, *, code_bytes=320):
 if c.get('format')!='REMESA_BOUND_GEARS_POSITIVE_V1' or c.get('physical_qualification') is not False or c.get('GPU_operations')!=0:
  raise ValueError('not an unqualified bound positive-witness catalogue')
 witness=c['witness']
 if code_bytes not in (320,344):raise ValueError('unsupported selected CODE size')
 code=checked(witness['code_path'],witness['code_sha256'],code_bytes)
 coeff=checked(witness['coefficient_path'],witness['coefficient_sha256'],144)
 vertices=checked(witness['vertices_path'],witness['vertices_sha256'],96)
 packed=b''.join(vertices[i*32:i*32+32]+bytes(16) for i in range(3))
 profiles=c['profiles']
 if [p['size'] for p in profiles]!=['1280x800','640x640']:raise ValueError('expected two exact sizes')
 text=['/* SPDX-License-Identifier: GPL-2.0-only */','/* Generated by tools/remesa/build_gears_scene_probe_profiles.py; LAB candidate, not physical approval. */',
 '#ifndef REMESA_GEARS_SCENE_PROBE_PROFILES_H','#define REMESA_GEARS_SCENE_PROBE_PROFILES_H',
 '#include "remesa_scene_probe_profiles.h"',
 'struct remesa_gears_scene_probe_profile {const u8 *packet;u32 packet_bytes;struct remesa_scene_probe_binding bindings[18];};']
 for i,p in enumerate(profiles):
  packet=checked(p['packet_path'],p['packet_sha256'],2264);placement=checked(p['placement_path'],p['placement_sha256'],776)
  if struct.unpack_from('<4I',packet,16)!=(1,18,11,2) or struct.unpack_from('<II',placement)!=(1,18):raise ValueError('wrong complete scene shape')
  width,height=(1280,800) if i==0 else (640,640)
  if struct.unpack_from('<4I',packet,320)!=(2,80,width,height) or struct.unpack_from('<I',packet,396)!=(1,) or struct.unpack_from('<I',packet,368)!=(104,):raise ValueError('wrong state/target contract')
  if len(p['bindings'])!=18:raise ValueError('wrong binding count')
  images={};addresses={};spans=[];ids=[]
  for j,b in enumerate(p['bindings']):
   va,n,rid,access=struct.unpack_from('<QQII',placement,8+j*24)
   if (va,n,rid,access)!=(b['gpu_va'],b['allocation_bytes'],b['captured_handle'],b['access']) or struct.unpack_from('<II',packet,32+j*8)!=(rid,access):raise ValueError('placement mismatch')
   if b['cached']!=1 or access not in [1,3] or not rid or rid in ids or va&4095 or n&4095 or not 0<n<=33554432 or va<0x20000000 or va+n>0xe0000000:raise ValueError('invalid backing')
   if any(va<end and start<va+n for start,end in spans):raise ValueError('overlapping backing')
   ids.append(rid);spans.append((va,va+n));addresses[rid]=va
   if access==1:images[rid]=checked(b['path'],b['sha256'],n)
  uses=[struct.unpack_from('<6I',packet,400+j*24) for j in range(11)]
  vs=[u for u in uses if u[2]==code_bytes and u[4]==0];params=[u for u in uses if u[2]==8 and u[4]==0]
  if len(vs)!=1 or len(params)!=1:raise ValueError('selected VS/parameter entry missing')
  rid,offset,n,_,_,_=vs[0]
  if images[rid][offset:offset+n]!=code:raise ValueError('CODE differs from preserved witness')
  source=images[params[0][0]]
  if len(source)<160 or struct.unpack_from('<I',source)[0]!=addresses[params[0][0]] or source[4:160]!=coeff+bytes(12):raise ValueError('coefficient upload differs from witness')
  _,_,_,rid,offset,n,count,reserved=struct.unpack_from('<8I',packet,1720+32)
  if n!=144 or count!=3 or reserved or images[rid][offset:offset+n]!=packed:raise ValueError('raw P/N packing differs from witness')
  text.append('static const u8 gears_scene_probe_packet_'+str(i)+'[] =')
  for at in range(0,len(packet),24):text.append(' "'+''.join(chr(92)+'x%02x'%v for v in packet[at:at+24])+'"')
  text[-1]+=';'
 text.append('static const struct remesa_gears_scene_probe_profile gears_scene_probe_profiles[2]={')
 for i,p in enumerate(profiles):
  text.append(' {gears_scene_probe_packet_'+str(i)+',sizeof(gears_scene_probe_packet_'+str(i)+')-1,{')
  for b in p['bindings']:
   digest=bytes.fromhex(b['sha256']) if b['access']==1 else bytes(32)
   text.append('  {0x%xULL,%du,%du,{%s}},'%(b['gpu_va'],b['allocation_bytes'],b['access'],','.join('0x%02x'%v for v in digest)))
  text.append(' }},')
 text.extend(['};','#endif','']);return '\n'.join(text)

def main():
 p=argparse.ArgumentParser(description=__doc__);p.add_argument('--catalogue',type=Path,required=True);p.add_argument('--output',type=Path,required=True);a=p.parse_args()
 result=build(json.loads(a.catalogue.read_text()))
 with a.output.open('x') as f:f.write(result)
 print('Generated separate two-profile18-binding gears LAB candidate; no hardware qualification')
if __name__=='__main__':main()
