"""Generate closed LAB metadata/image identities from verified Mesa fixtures.
No hardware interaction. Refuses changed inputs and overwriting its output.
"""
import argparse,hashlib,json,struct
from pathlib import Path

def main():
 p=argparse.ArgumentParser(description=__doc__);p.add_argument('--catalogue',type=Path,required=True);p.add_argument('--output',type=Path,required=True);p.add_argument('--initialized-catalogue',type=Path,required=True);p.add_argument('--finalized-catalogue',type=Path,required=True);p.add_argument('--gallium-catalogue',type=Path);a=p.parse_args()
 c=json.loads(a.catalogue.read_text());initial=json.loads(a.initialized_catalogue.read_text());final=json.loads(a.finalized_catalogue.read_text())
 for group in [c,initial,final]:assert not group['physical_qualification'] and group['GPU_operations']==0 and [p['size'] for p in group['profiles']]==['1280x800','640x640']
 assert not c.get('initialization_predecessor',False) and initial['initialization_predecessor']
 assert not c.get('depth_finalize',False) and not initial.get('depth_finalize',False)
 assert final['initialization_predecessor'] and final['depth_finalize']
 c['profiles']+=initial['profiles']+final['profiles']
 if a.gallium_catalogue:
  gallium=json.loads(a.gallium_catalogue.read_text())
  assert not gallium['physical_qualification'] and gallium['GPU_operations']==0
  assert gallium['bound_gallium_inputs'] and gallium['initialization_predecessor'] and gallium['depth_finalize']
  assert [f['size'] for f in gallium['profiles']]==['1280x800','640x640']
  c['profiles']+=gallium['profiles']
 sha=lambda b:hashlib.sha256(b).hexdigest()
 text=['/* SPDX-License-Identifier: GPL-2.0-only */','/* Generated by tools/remesa/build_scene_probe_profiles.py; LAB only. */','#ifndef REMESA_SCENE_PROBE_PROFILES_H','#define REMESA_SCENE_PROBE_PROFILES_H',
 'struct remesa_scene_probe_binding {u64 address;u32 bytes,access;u8 digest[32];};',
 'struct remesa_scene_probe_profile {const u8 *packet;u32 packet_bytes;struct remesa_scene_probe_binding bindings[17];};']
 for i,f in enumerate(c['profiles']):
  b=Path(f['packet_path']).read_bytes();assert len(b)==2264 and sha(b)==f['packet_sha256']
  assert struct.unpack_from('<I',b,320)[0]==(2 if i>=4 else 1)
  assert struct.unpack_from('<I',b,396)[0]==(1 if i>=4 else 0)
  placement=Path(f['placement_path']).read_bytes();assert len(placement)==776 and sha(placement)==f['placement_sha256']
  assert struct.unpack_from('<II',placement)==(1,17) and struct.unpack_from('<4I',b,16)==(1,17,10,2)
  for n,expected in enumerate(f['bindings']):
   assert struct.unpack_from('<QQII',placement,8+24*n)==(expected['gpu_va'],expected['allocation_bytes'],expected['captured_handle'],expected['access'])
   assert struct.unpack_from('<II',b,32+8*n)==(expected['captured_handle'],expected['access'])
  text.append('static const u8 scene_probe_packet_'+str(i)+'[] =')
  for at in range(0,len(b),24):text.append(' "'+''.join(chr(92)+'x%02x'%x for x in b[at:at+24])+'"')
  text[-1]+=';'
 text.append('static const struct remesa_scene_probe_profile scene_probe_profiles['+str(len(c['profiles']))+']={')
 for i,f in enumerate(c['profiles']):
  assert len(f['bindings'])==17
  text.append(' {scene_probe_packet_'+str(i)+',sizeof(scene_probe_packet_'+str(i)+')-1,{')
  for b in f['bindings']:
   assert b['cached']==1 and b['access'] in [1,3] and 0<b['allocation_bytes']<=33554432
   digest=bytes(32)
   if b['access']==1:
    data=Path(b['path']).read_bytes();assert len(data)==b['allocation_bytes'] and sha(data)==b['sha256'];digest=bytes.fromhex(b['sha256'])
   text.append('  {0x%xULL,%du,%du,{%s}},'%(b['gpu_va'],b['allocation_bytes'],b['access'],','.join('0x%02x'%v for v in digest)))
  text.append(' }},')
 text.extend(['};','#endif',''])
 with a.output.open('x') as out:out.write('\n'.join(text))
 print('Generated '+str(len(c['profiles']))+' closed profiles; hardware qualification remains required')
if __name__=='__main__':main()
